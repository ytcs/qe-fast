# Regenerate qefast/w90/wannierise.F90 from wannier90 3.1's src/wannierise.F90:
#   python3 patch_wannierise.py <original wannierise.F90> <output>
import sys
s = open(sys.argv[1]).read()
hdr = """! Modified for qe-fast, 2026-11-06 to 2026-11-06; see NOTICE.
! qe-fast: copy of external/wannier90/src/wannierise.F90 (wannier90 3.1, 1d6b1873), GENERATED by
! qefast/w90/patch_wannierise.py and compiled in its place (external/wannier90.cmake). Change: when QEF_W90_WNT > 1,
! the per-k loops of wann_main's internal_new_u_and_m (exp(dq) eigen-solve per k, U update, M update per (k, b))
! and of wann_domega's gradient run as OpenMP copies of the original loops (EPW runs wannier90 on its ionode only,
! while the other ranks wait). Each k writes only its own blocks with the same BLAS/LAPACK calls and no reduction
! over k is reordered; the threaded copies can still round differently in the last bit (compiler code generation
! of the outlined loop bodies). With QEF_W90_WNT unset the original serial loops run unchanged
!.
"""
s = hdr + s


def sub(blk, x, y, cnt=1):
    assert blk.count(x) == cnt, (blk.count(x), x[:90])
    return blk.replace(x, y)


def dup(blk, start, end, directive):
    """Wrap blk[start:end] (an original loop) as: if (qef_wnt > 1) then <directive + copy + end> else <orig> endif"""
    i = blk.index(start)
    j = blk.index(end, i) + len(end)
    orig = blk[i:j]
    new = ("      if (qef_wnt > 1) then\n" + directive + orig + "!$omp end parallel do\n"
           "      else\n" + orig + "      endif\n")
    return blk[:i] + new + blk[j:]


s = sub(s, "  public :: wann_main\n", """  public :: wann_main
  ! qef: OpenMP threads for the per-k loops of wann_main (QEF_W90_WNT; 1 = serial original loops, the default)
  integer, save :: qef_wnt = 1
""")

a = s.index("  subroutine wann_main\n"); b = s.index("  end subroutine wann_main\n")
m = s[a:b]
m = sub(m, "    ! main iteration loop\n    do iter = 1, num_iter\n", """    ! qef: threads for the per-k loops (QEF_W90_WNT)
    block
      character(len=16) :: ntval
      integer :: ios_nt
      qef_wnt = 1
      call qef_getenv('QEF_W90_WNT', ntval, status=ios_nt)
      if (ios_nt == 0) then
        read (ntval, *, iostat=ios_nt) qef_wnt
        if (ios_nt /= 0) qef_wnt = 1
      endif
      qef_wnt = max(1, qef_wnt)
      if (lsitesymmetry) qef_wnt = 1
      if (qef_wnt > 1 .and. on_root) write (stdout, '(1x,a,i3,a)') 'qef: wann_main k-loops on ', qef_wnt, &
        ' OpenMP threads'
    end block

    ! main iteration loop
    do iter = 1, num_iter
""")

u0 = m[m.index("    subroutine internal_new_u_and_m()"):m.index("    end subroutine internal_new_u_and_m")]
u = u0
u = dup(u, "      do nkp_loc = 1, counts(my_node_id)\n        nkp = nkp_loc + displs(my_node_id)\n        if (lsitesymmetry) then",
        "          call utility_zgemm(cdq_loc(:, :, nkp_loc), cmtmp, 'N', tmp_cdq, 'C', num_wann)\n        endif\n      enddo\n",
        "!$omp parallel do num_threads(qef_wnt) schedule(dynamic) &\n"
        "!$omp   private(nkp, i, info, ltmp, nsdim, tmp_cdq, cmtmp, evals, cwork, rwork, cz, cwschur1, cwschur2, cwschur3, cwschur4)\n")
u = dup(u, "      do nkp_loc = 1, counts(my_node_id)\n        nkp = nkp_loc + displs(my_node_id)\n        ! cmtmp = U(k) . cdq(k)",
        "        u_matrix_loc(:, :, nkp_loc) = cmtmp(:, :)\n      enddo\n",
        "!$omp parallel do num_threads(qef_wnt) schedule(static) private(nkp, cmtmp)\n")
u = dup(u, "      do nkp_loc = 1, counts(my_node_id)\n        nkp = nkp_loc + displs(my_node_id)\n        do nn = 1, nntot\n          nkp2 = nnlist(nkp, nn)",
        "          m_matrix_loc(:, :, nn, nkp_loc) = cmtmp(:, :)\n        enddo\n      enddo\n",
        "!$omp parallel do num_threads(qef_wnt) schedule(static) private(nkp, nn, nkp2, tmp_cdq, cmtmp)\n")
m = m.replace(u0, u)
s = s[:a] + m + s[b:]

a = s.index("  subroutine wann_domega(csheet, sheet, rave, cdodq)"); b = s.index("  end subroutine wann_domega")
d = s[a:b]
d = dup(d, "    do nkp_loc = 1, counts(my_node_id)\n      nkp = nkp_loc + displs(my_node_id)\n      do nn = 1, nntot\n        do n = 1, num_wann ! R^{k,b}",
        "      enddo\n    enddo\n    cdodq_loc = cdodq_loc/real(num_kpts, dp)*4.0_dp\n".replace("    cdodq_loc = cdodq_loc/real(num_kpts, dp)*4.0_dp\n", ""),
        "!$omp parallel do num_threads(qef_wnt) schedule(static) private(nkp, nn, n, m, mnn) firstprivate(cr, crt)\n")
s = s[:a] + d + s[b:]
s = sub(s, "\nmodule w90_wannierise\n", "\nmodule w90_wannierise\n  USE qef_config, ONLY : qef_getenv\n")
open(sys.argv[2], 'w').write(s)
print("patched")
